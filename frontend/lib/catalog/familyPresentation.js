export function getFamilyPresentationEvidence(product) {
  if (!product || typeof product !== 'object' || !Object.hasOwn(familyPresentationBindings, product.id)) return null;
  const prototype = Object.getPrototypeOf(product);
  if (prototype !== Object.prototype && prototype !== null) return null;
  for (const key of ['id', 'source', 'sourceId', 'sourceFileId', 'sourceSha256']) if (!Object.hasOwn(product, key)) return null;
  if (product.source === 'api') {
    if (!Object.hasOwn(product, 'databaseId') || !Object.hasOwn(product, 'sourceMediaPath')) return null;
  } else if (product.source !== 'official' || Object.hasOwn(product, 'databaseId')) return null;
  try {
    return verifiedTransformerAsset(product, familyPresentationBindings[product.id], sourceIdentity);
  } catch {
    return null;
  }
}

export function getFamilyTechnicalDocument(product) {
  const evidence = getFamilyPresentationEvidence(product);
  const page = evidence?.technicalPage;
  if (!page || !product.sourcePages.includes(page)) return null;
  const image = sourcePageImage(product, page);
  const href = sourcePageUrl(product, page);
  return image && href ? { page, image, href, caption: `Технические данные семейства · страница ${page} исходного каталога; не фотография изделия` } : null;
}
