import { test, expect } from '@playwright/test';
const api = process.env.E2E_API_URL || 'http://localhost:8000/api/v1';
async function signIn(page, email = 'catalog@demo.example') {
 await page.goto('/login?next=/admin/catalog');
 await page.getByLabel('Email').fill(email);
 await page.getByLabel('Пароль').fill('ChangeMe123!');
 await page.getByRole('button', { name: 'Войти', exact: true }).click();
}
async function apiSession(request) {
 const response = await request.post(`${api}/auth/login`, { data: { email: 'catalog@demo.example', password: 'ChangeMe123!' } });
 expect(response.ok()).toBeTruthy();
 const token = await response.json();
 return { Authorization: `Bearer ${token.access_token}` };
}
test('anonymous and tenant administrators cannot edit the platform catalog', async ({ page }) => {
 await page.goto('/admin/catalog');
 await expect(page.getByRole('link', { name: 'Войти', exact: true })).toBeVisible();
 await signIn(page, 'admin@demo.example');
 await expect(page.getByRole('heading', { name: 'Нет доступа к управлению каталогом' })).toBeVisible();
 await expect(page.getByRole('button', { name: 'Добавить товар +' })).toHaveCount(0);
});
